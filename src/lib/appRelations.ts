/**
 * Cross-module business workflows for GENERATED applications.
 *
 * Modules are not isolated tables: an order knows about customers and
 * products, a payment knows about invoices, and saving an order moves stock.
 * These pure helpers describe those links; the runtime server functions apply
 * them on every write.
 */

/** field key -> module kinds the value should come from */
export type RelationMap = Record<string, string[]>;

const CUSTOMER_SOURCES = ["customers", "crm", "clients", "leads", "members", "patients", "students", "tenants"];
const ITEM_SOURCES = ["products", "menu", "inventory", "medicines", "plans", "courses", "rooms", "assets"];

export const RELATIONS: Record<string, RelationMap> = {
  orders: { customer: CUSTOMER_SOURCES, product: ITEM_SOURCES, item: ITEM_SOURCES },
  sales: { customer: CUSTOMER_SOURCES, product: ITEM_SOURCES, item: ITEM_SOURCES },
  invoices: { customer: CUSTOMER_SOURCES },
  quotes: { customer: CUSTOMER_SOURCES },
  payments: { customer: CUSTOMER_SOURCES, invoice: ["invoices"] },
  deals: { customer: CUSTOMER_SOURCES, company: ["companies"] },
  reservations: { customer: CUSTOMER_SOURCES, table: ["tables"] },
  bookings: { customer: CUSTOMER_SOURCES, service: ITEM_SOURCES, staff: ["staff", "employees", "doctors"] },
  tickets: { customer: CUSTOMER_SOURCES },
  reviews: { customer: CUSTOMER_SOURCES, product: ITEM_SOURCES },
  inventory: { product: ITEM_SOURCES, warehouse: ["warehouse"] },
  purchases: { supplier: ["suppliers", "companies"], product: ITEM_SOURCES },
  shipments: { customer: CUSTOMER_SOURCES, order: ["orders"] },
  prescriptions: { patient: ["patients"], doctor: ["doctors"], medicine: ["medicines"] },
  lab_tests: { patient: ["patients"], doctor: ["doctors"] },
  grades: { student: ["students"], course: ["courses"] },
  attendance: { student: ["students"], class: ["classes"] },
  fees: { student: ["students"] },
  leases: { property: ["properties"], tenant: ["tenants"] },
  maintenance: { property: ["properties"] },
  subscriptions: { customer: CUSTOMER_SOURCES, plan: ["plans"] },
  contracts: { customer: CUSTOMER_SOURCES },
  timesheets: { customer: CUSTOMER_SOURCES, project: ["projects"] },
  attendees: { event: ["events"] },
  kitchen: { order: ["orders"] },
};

/** Which module kinds can fill a given field on a given module. */
export function relationSourcesFor(kind: string, fieldKey: string): string[] {
  const map = RELATIONS[kind];
  if (!map) return [];
  const direct = map[fieldKey];
  if (direct) return direct;
  // tolerate variants generated by the AI: customer_name, product_name, ...
  const base = fieldKey.replace(/_(name|id|title)$/, "");
  return map[base] ?? [];
}

export const LABEL_KEYS = ["name", "title", "product", "item", "customer", "number", "reference", "description"];

export function labelOfRecord(data: Record<string, unknown>): string {
  for (const k of LABEL_KEYS) {
    const v = data[k];
    if (typeof v === "string" && v.trim()) return v.trim();
  }
  return "";
}

const STOCK_KEYS = ["stock", "quantity", "qty", "stock_qty", "on_hand", "available"];

export function stockKeyOf(data: Record<string, unknown>): string | null {
  for (const k of STOCK_KEYS) if (data[k] !== undefined && data[k] !== null && data[k] !== "") return k;
  return null;
}

const QTY_KEYS = ["quantity", "qty", "units", "count", "guests", "people"];

/** Record-level quantity field, if any. */
function recordQty(data: Record<string, unknown>): number {
  for (const k of QTY_KEYS) {
    const n = Number(data[k]);
    if (Number.isFinite(n) && n > 0) return n;
  }
  return 1;
}

/** Parses free-text item entries like "AirPods Pro (2)", "2x AirPods Pro" or "AirPods Pro x2". */
export function parseItemText(s: string): { name: string; qty: number } {
  const t = s.trim();
  let m = t.match(/^(.*?)\s*\((\d+)\)$/) ?? t.match(/^(.*?)\s*[x×]\s*(\d+)$/i);
  if (m) return { name: m[1].trim(), qty: Number(m[2]) };
  m = t.match(/^(\d+)\s*[x×]\s*(.+)$/i);
  if (m) return { name: m[2].trim(), qty: Number(m[1]) };
  return { name: t, qty: 1 };
}

export function quantityOf(data: Record<string, unknown>): number {
  const list = referencedItems(data);
  if (list.length > 0) return list.reduce((a, e) => a + e.qty, 0);
  return 1;
}

/** Kinds that consume stock when created, and kinds that replenish it. */
export const STOCK_OUT_KINDS = new Set(["orders", "sales"]);
export const STOCK_IN_KINDS = new Set(["purchases", "inventory"]);

/** The item line(s) referenced by an order/sale-like record: either a linked
 * product field, or one or more comma-separated free-text entries like
 * "iPhone 15 (1), 30W Fast Charger USB-C (2)". */
export function referencedItems(data: Record<string, unknown>): Array<{ name: string; qty: number }> {
  for (const k of ["product", "item", "product_name", "menu_item", "name", "title"]) {
    const v = data[k];
    if (typeof v === "string" && v.trim()) {
      const p = parseItemText(v);
      return [{ name: p.name, qty: p.qty !== 1 ? p.qty : recordQty(data) }];
    }
  }
  const items = data["items"];
  if (typeof items === "string" && items.trim()) {
    const parts = items.split(",").map((s) => s.trim()).filter(Boolean);
    if (parts.length > 1) return parts.map((p) => parseItemText(p)).filter((x) => x.name);
    const p = parseItemText(parts[0] ?? "");
    return p.name ? [{ name: p.name, qty: p.qty !== 1 ? p.qty : recordQty(data) }] : [];
  }
  return [];
}

/** Single-item convenience wrapper around referencedItems. */
export function referencedItem(data: Record<string, unknown>): string {
  return referencedItems(data)[0]?.name ?? "";
}

/** The customer name referenced by a record. */
export function referencedCustomer(data: Record<string, unknown>): string {
  for (const k of ["customer", "customer_name", "client", "guest", "patient", "student", "name"]) {
    const v = data[k];
    if (typeof v === "string" && v.trim()) return v.trim();
  }
  return "";
}

export function norm(s: string): string {
  return s.trim().toLowerCase();
}
