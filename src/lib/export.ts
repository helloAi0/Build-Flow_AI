import type { Tables } from "@/integrations/supabase/types";

type Project = Tables<"projects">;
type Module = Tables<"project_modules">;
type Record_ = Tables<"module_records">;

export function downloadJSON(project: Project | null, modules: Module[], records: Record_[]) {
  const payload = {
    exportedAt: new Date().toISOString(),
    project,
    modules,
    records,
  };
  triggerDownload(
    new Blob([JSON.stringify(payload, null, 2)], { type: "application/json" }),
    `${slug(project?.name ?? "project")}.json`,
  );
}

export function downloadMarkdown(project: Project | null, modules: Module[], records: Record_[]) {
  const lines: string[] = [];
  lines.push(`# ${project?.name ?? "Untitled project"}`);
  lines.push("");
  if (project?.description) { lines.push(project.description); lines.push(""); }
  lines.push(`_Exported ${new Date().toLocaleString()}_`);
  lines.push("");
  lines.push("## Structure");
  lines.push("");
  for (const m of modules) {
    const count = records.filter((r) => r.module_id === m.id).length;
    lines.push(`- **${m.title}** (\`${m.kind}\`) — ${count} record${count === 1 ? "" : "s"}`);
  }
  lines.push("");
  for (const m of modules) {
    const rows = records.filter((r) => r.module_id === m.id);
    if (!rows.length) continue;
    lines.push(`## ${m.title}`);
    lines.push("");
    for (const r of rows) {
      lines.push("- " + Object.entries(r.data as Record<string, unknown>).map(([k, v]) => `**${k}:** ${format(v)}`).join(" · "));
    }
    lines.push("");
  }
  triggerDownload(
    new Blob([lines.join("\n")], { type: "text/markdown" }),
    `${slug(project?.name ?? "project")}.md`,
  );
}

